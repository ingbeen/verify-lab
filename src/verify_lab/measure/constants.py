# 「확정 전 필수 항목」으로 올렸다. 검증마다 이름을 두면 산식만 공통이고 컬럼은 두 벌이
# 되는 **절반짜리 통합**이 되며, 그 상태에서는 한쪽 이름이 바뀌어도 예외가 나지 않는다.
# 그리고 매매법이 서로의 이름을 가져다 쓰면 **매매법끼리 import** 가 되어 계층 계약이 깨진다.
#
