"""측정 계층 공통 상수

`measure` 가 내는 long-form 결과의 스키마를 단일 관리한다. 컬럼명과 제외 사유가
파일마다 흩어지면 같은 표를 만드는 코드와 읽는 코드가 조용히 갈라진다.

이 스키마는 2-b(통계 집계)와 2-c(출력)의 입력이기도 하다. 계약과 그 근거는
`src/verify_lab/CLAUDE.md` 「계층 간 계약」의 forward return 반환 계약이 SoT 다.
"""

# ============================================================
# forward return 결과 스키마 (내부 계산용 영문 토큰)
# ============================================================

# 신호일은 시세 스키마의 날짜 컬럼(`common_constants.COL_DATE`)을 그대로 쓴다 —
# 새 이름을 만들면 시세와 대조할 때마다 변환이 붙는다
COL_BASIS = "Basis"
COL_HORIZON = "Horizon"
COL_FORWARD_RETURN = "ForwardReturn"
COL_EXCLUDED_REASON = "ExcludedReason"

# ============================================================
# 제외 사유
# ============================================================

# 유효한 칸은 빈 문자열이다. 제외된 행은 지우지 않고 값만 비운 뒤 사유를 단다 —
# 행이 사라지면 표본이 조용히 줄어 생존편향이 생긴다
REASON_NONE = ""
REASON_OUT_OF_RANGE = "구간 끝이 데이터 범위를 넘음"

# ============================================================
# 제외 건수 요약 스키마
# ============================================================

COL_SIGNAL_COUNT = "SignalCount"
COL_EXCLUDED_COUNT = "ExcludedCount"

EXCLUDED_SUMMARY_COLUMNS = [COL_BASIS, COL_HORIZON, COL_SIGNAL_COUNT, COL_EXCLUDED_COUNT]

# ============================================================
# 판정가능 — 「이 칸으로 판단해도 되는가」
# ============================================================

# 표본이 하한에 못 미쳐도 **행은 남기고** 이 컬럼으로 「판정에 쓰지 말라」를 표에 적는다
# (루트 `CLAUDE.md` 측정의 원칙 17). 행이 사라지면 그 칸을 못 봤다는 사실 자체를 사용자가 모르고,
# 0 으로 채우면 「손실도 이익도 없었다」로 읽힌다.
#
# **공통 계층이 소유한다.** 원칙 17 이 모든 검증에 요구하는 것이라 검증마다 새로 만들면
# 같은 원칙이 다른 답을 낸다 — 값이 문자열과 불린으로 갈리면 같은 이름의 컬럼을 나란히 읽을 수 없고,
# `screening` 이 「예」로 거르므로 불린이 담긴 표는 전 칸이 조용히 제외된다.
# 정의처가 하나임은 `tests/test_layer_contracts.py` 가 검사한다
COL_JUDGEABLE = "Judgeable"

JUDGEABLE_YES = "예"
JUDGEABLE_NO = "아니오"

# ============================================================
# 칸당 표본 하한
# ============================================================

# 이 수에 못 미치는 칸은 판정에 쓰지 않는다. 검정을 붙이지 않고(`statistics`), 축을 쪼개지 않으며,
# `판정가능` 이 「아니오」가 된다.
#
# **하나인 이유**: 루트 `CLAUDE.md` 측정의 원칙 12 가 「칸당 유효 표본 10건」을 명시하고
# 원칙 17 이 「원칙 12 의 10건」이라며 같은 값임을 선언한다. 검정 하한도 (기준 × 구간) 칸의
# 표본이므로 재는 대상이 같다. 이름을 계층마다 달리 두면 값이 갈라져도 예외가 나지 않는다
MIN_SAMPLE_PER_CELL = 10

# ============================================================
# 방향 비율의 절반선
# ============================================================

# 「절반 넘게 내렸다」를 판정하는 선 (비율, 0.5 = 50%). 측정의 원칙 13 이 요구하는
# **평균-비율 어긋남** 판정의 임계값이며, 그 판정은 `statistics.mean_rate_conflict` 가 소유한다.
#
# **공통 계층이 갖는 이유**: 검증마다 두면 값도 판정 함수도 한 벌씩 생긴다 —
# 원칙이 모든 검증에 요구하는 것을 검증마다 구현하면 같은 원칙이 다른 답을 낸다
HALF_RATE = 0.5

# 그 판정이 실리는 컬럼. **임계값·판정 함수와 «함께» 올라와야 한다** —
# 이름만 검증에 남는 절반짜리 통합에서는 한쪽 컬럼 이름이 바뀌어도 예외가 나지 않는다.
# 한글 레이블은 표시용이라 `report/constants.py` 가 갖는다
COL_MEAN_RATE_CONFLICT = "mean_rate_conflict"

# ============================================================
# 시기 구간 (측정의 원칙 17)
# ============================================================

# 균등 2분할의 이름. 원칙 17 이 **모든 매매법**에 요구하는 축이라 검증·매매가 같은 말을 써야 한다.
#
# **표시 레이블이 아니라 데이터 칸에 들어가는 값이라 여기 있다.** 위 `JUDGEABLE_YES` 와 같은
# 성격이며, 매매 계층과 두 검증이 각자 이름을 두면 **세 벌**이 된다 — 계층마다 이름이
# 달라지므로 **이름으로 찾으면 세 벌이 있어도 한 건도 안 걸린다.** 산출물에 나가는 것은 값이다.
#
# **구간 «목록»은 여기 두지 않는다.** 몇 구간을 낼지는 계층의 구성이라
# 매매 계층의 `execution/constants.PERIODS` 가 정한다 — 올린 것은 이름 둘뿐이다
PERIOD_FIRST_HALF = "앞 절반"
PERIOD_SECOND_HALF = "뒤 절반"

# ============================================================
# 배당락 (측정의 원칙 14)
# ============================================================

# 보유 구간에 들어간 배당락을 담는 세 컬럼. 산식은 `measure/distribution.py` 의
# `dividend_impact` 가 소유하고, 이름은 여기가 소유한다.
#
# **공통 계층이 갖는 이유**: 원칙 14 가 「배당락이 보유 구간에 들어가면 그 사실과 규모를
# 결과 문서에 적는다」를 **모든 매매법**에 요구하고, `.claude/rules/trading.md` 가 그것을
# 「확정 전 필수 항목」으로 올렸다. 검증마다 이름을 두면 산식만 공통이고 컬럼은 두 벌이
# 되는 **절반짜리 통합**이 되며, 그 상태에서는 한쪽 이름이 바뀌어도 예외가 나지 않는다.
# 그리고 매매법이 서로의 이름을 가져다 쓰면 **매매법끼리 import** 가 되어 계층 계약이 깨진다.
#
# [중요] **대조 건수를 함께 낸다.** 「걸린 건수 0」과 「수정주가가 없어 못 쟀다」는 다른
# 사실이고, 그 구별이 없으면 없는 안전을 보고한다
COL_DIVIDEND_MEASURED = "dividend_measured"
COL_DIVIDEND_HIT_COUNT = "dividend_hit"
COL_DIVIDEND_MEAN_IMPACT = "dividend_mean_impact"

# 왜곡의 반올림 자릿수. **백분율 2자리가 아니라 4자리다** — 실측 왜곡이 0.05%p 대라
# 2자리로는 걸린 칸과 안 걸린 칸이 똑같이 `0.0` 이 된다.
# 이 값은 이미 %p 단위라 저장 계층의 비율→백분율 변환을 타지 않는다
DIVIDEND_IMPACT_DECIMALS = 4

# ============================================================
# 달력형 진입·청산 일정
# ============================================================

# 진입과 청산이 **거래일 수가 아니라 달력**으로 정해지는 매매법이 쓰는 컬럼이다.
# `forward_return` 은 고정 거래일 구간만 재므로 그 틀에 들어가지 않는다.
#
# **공통 계층이 갖는 이유**: 달력형 매매법마다 같은 뜻의 컬럼을 따로 두면 산출물 헤더가
# 조용히 갈리고, 매매법끼리는 서로를 import 할 수 없다(`tests/test_layer_contracts.py`)

# 진입 달. 청산이 익월로 넘어가도 **그 매매가 속한 달은 진입 달**이다
COL_MONTH = "month"

# 실제로 판 날. 목표일이 휴장이면 직전 거래일이다
COL_EXIT_DATE = "exit_date"

# 진입일부터 청산일까지의 거래일 수. **신호마다 다르다** — 청산이 달력 기준이기 때문이다
COL_HOLD_DAYS = "hold_days"

# 사용자가 차트로 직접 대조하는 원자료 (측정의 원칙 8)
