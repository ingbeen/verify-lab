"""수집 계층이 공유하는 상수

**여러 수집기가 같은 값을 쓰는 것만 둔다.** 한 수집기에서만 쓰는 값은 그 파일 상단에 남긴다
(`src/verify_lab/CLAUDE.md` 「상수 관리」). 쓰이는 곳이 하나인 값을 여기 올리면 그 파일을
읽는 사람이 공유값이라고 오해하고, 고칠 때 다른 수집기를 함께 확인하게 된다.

여기 있는 것은 **KRX 를 상대하는 세 수집기**(`pykrx`·`etn`·`krx_futures`)의 공통 규격과
그들이 함께 지키는 저장 경계다.
"""

from typing import Final

# ============================================================
# 저장 경계
# ============================================================

# 국내 수집에서 저장에 넣지 않을 최근 구간 (달력일).
#
# 국내는 시차가 없어 전일 종가가 확정이지만, **장중에도 당일 행이 그대로 반환되는 것이 실측**됐다
# (`src/verify_lab/CLAUDE.md` 「계층 간 계약」의 원시 시세 저장 규칙). 미확정 종가가 남으면
# 그날이 극단 이벤트로 잡힌다. 선물은 여기에 더해 **당일 정산가가 0 으로 온다.**
#
# **미국은 이 값을 쓰지 않는다** — 시차로 하루가 더 붙어 `yfinance_collector` 가 자기 값을 둔다.
# 쓰는 곳이 그 파일 하나뿐이라 계층 상수로 올리지 않았다
DOMESTIC_RECENT_EXCLUSION_DAYS: Final = 1

# ============================================================
# KRX 날짜 규격
# ============================================================

# 요청에 넣는 날짜 형식. KRX 가 정한 규격이라 우리가 고를 수 있는 값이 아니다
KRX_REQUEST_DATE_FORMAT: Final = "%Y%m%d"

# 응답으로 오는 날짜 형식. **요청과 다르다** — 두 규격을 한 상수로 합치면
# 한쪽이 바뀔 때 다른 쪽이 조용히 끌려간다
KRX_RESPONSE_DATE_FORMAT: Final = "%Y/%m/%d"
